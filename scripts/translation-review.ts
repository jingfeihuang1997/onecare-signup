// Writes docs/TRANSLATION-REVIEW.md from the dictionaries, so the list never drifts from
// the code. Run with: npm run i18n:review
import { writeFileSync } from 'node:fs';
import { en, type StringKey } from '../src/i18n/en';
import { entryText, needsReview } from '../src/i18n/entry';
import { es } from '../src/i18n/es';
import { zhHans } from '../src/i18n/zh-Hans';

const keys = (Object.keys(en) as StringKey[]).filter(
  (key) => needsReview(es[key]) || needsReview(zhHans[key]),
);
const health = keys.filter((key) => key.startsWith('health.'));
const consent = keys.filter((key) => !key.startsWith('health.'));

const block = (key: StringKey) =>
  [
    `### \`${key}\``,
    '',
    `- **English:** ${en[key]}`,
    `- **Español:** ${entryText(es[key])}`,
    `- **中文:** ${entryText(zhHans[key])}`,
    '',
  ].join('\n');

const text = [
  '# Translations that need professional review',
  '',
  'Generated by `npm run i18n:review` from `src/i18n`. Do not edit by hand: change the',
  'dictionaries and run the command again.',
  '',
  'SPEC section 9 says the Spanish and Chinese wording of the health questions and the',
  'consents needs professional translation. Claude wrote the versions below so the screens',
  'can be shown. Each is marked `needsReview: true` in its dictionary (the `review(...)`',
  'wrapper). When a translator has approved an entry, replace the wrapper with the plain',
  'string and run the command again; a unit test lists which entries must stay marked.',
  '',
  `${keys.length} entries: ${health.length} health questions and ${consent.length} consent and signature texts.`,
  '',
  'Everything else in `es.ts` and `zh-Hans.ts` was also translated by Claude and should be',
  'read by a native speaker before launch, but it is ordinary interface text.',
  '',
  '## Notes for the translator',
  '',
  '- The English health questions are kept exactly as the current site words them,',
  '  including their punctuation. The translations aim for the meaning, not the punctuation.',
  '- Question 10 begins "For women:" and is shown to everyone, as in English.',
  '- The questions say "you" even when a helper answers for the patient, as in English.',
  '- Spanish uses the formal "usted". Question 1 uses the masculine "enfermo".',
  '- The consent wording itself is a draft that is pending OneCare legal review, so the',
  '  English may change before translation is final.',
  '- Words in {braces} are filled in by the app and must stay as they are.',
  '',
  '## Health questions',
  '',
  ...health.map(block),
  '## Consents and signature',
  '',
  ...consent.map(block),
].join('\n');

writeFileSync('docs/TRANSLATION-REVIEW.md', text, 'utf8');
console.log(`docs/TRANSLATION-REVIEW.md: ${keys.length} entries`);
